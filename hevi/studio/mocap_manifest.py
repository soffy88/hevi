"""Motion-library manifest for the CMU mocap clips in ``assets/mocap-clips``.

Writes ``assets/mocap-clips/manifest.json``: one entry per clip with Chinese
name, category, file, skeleton, fps, frames, source trial, Chinese label and
the CMU licence/acknowledgement.  The manifest is what tests validate and what
documentation links against; the clips themselves are generated by
:mod:`hevi.studio.cmumocap`.

Usage::

    PYTHONPATH=. .venv/bin/python -m hevi.studio.mocap_manifest
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from hevi.studio.cmumocap import _KEEP, available

#: clip name -> (Chinese name, category)
_INFO: dict[str, tuple[str, str]] = {
    "walk": ("走路", "locomotion"),
    "run": ("跑步", "locomotion"),
    "sprint": ("冲刺", "locomotion"),
    "march": ("原地踏步", "locomotion"),
    "shuffle": ("悄悄挪动", "locomotion"),
    "jump": ("跳跃", "locomotion"),
    "kick": ("踢腿", "combat"),
    "punch": ("拳击", "combat"),
    "roll": ("翻滚", "stunt"),
    "knockdown": ("被击倒", "stunt"),
    "getup": ("起身", "stunt"),
    "victory": ("欢呼跳跃", "celebration"),
    "sit": ("坐下", "pose"),
    "wave": ("挥手", "gesture"),
    "twist": ("扭动身体", "dance"),
    "dance_spin": ("转圈舞", "dance"),
    "dance_glide": ("滑步舞", "dance"),
}

#: clip name -> CMU search-index motion description (for trial provenance)
_TRIAL_DESC: dict[str, str] = {
    "sprint": "Run",
    "punch": "boxing",
    "roll": "Roll over",
    "knockdown": "fall on face",
    "getup": "Get up from floor",
    "victory": "high jump (used as victory/celebration)",
}

CMU_LICENSE = (
    "CMU Graphics Lab Motion Capture Database: free for all uses (research and "
    "commercial). Acknowledgement required: 'This data was created with funding "
    "from NSF EIA-0196217. The database was compiled by the CMU Graphics Lab.'"
)

SKELETON = "cmu-2d-16joints"
JOINTS = list(_KEEP)


def manifest_path() -> Path:
    return Path(__file__).resolve().parents[2] / "assets" / "mocap-clips" / "manifest.json"


def _clip_meta(path: Path) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    return {
        "name": data.get("name") or path.stem,
        "fps": data.get("fps"),
        "frameCount": data.get("frameCount"),
        "label": data.get("label", ""),
        "plane": data.get("plane", ""),
        "duration_s": round((data.get("frameCount") or 0) / (data.get("fps") or 30), 3),
    }


def build_manifest() -> dict[str, Any]:
    avail = available()
    clip_dir = Path(__file__).resolve().parents[2] / "assets" / "mocap-clips" / "clips"
    motions: list[dict[str, Any]] = []
    for path in sorted(clip_dir.glob("*.json")):
        name = path.stem
        name_cn, category = _INFO.get(name, (name, "misc"))
        meta = _clip_meta(path)
        trial = avail.get(name, {})
        motions.append(
            {
                "name": name,
                "name_cn": name_cn,
                "category": category,
                "file": f"assets/mocap-clips/clips/{path.name}",
                "skeleton": SKELETON,
                "joints": JOINTS,
                "fps": meta["fps"],
                "frames": meta["frameCount"],
                "duration_s": meta["duration_s"],
                "source": trial.get("source", f"CMU {meta['name']}"),
                "cmu_trial_description": _TRIAL_DESC.get(name),
                "label": meta["label"],
                "license": CMU_LICENSE,
            }
        )
    return {
        "library": "assets/mocap-clips",
        "skeleton": SKELETON,
        "joints": JOINTS,
        "license": CMU_LICENSE,
        "source_note": (
            "2-D joint tracks derived from CMU BVH trials by "
            "hevi/studio/cmumocap.py (clean-room parser, forward kinematics, "
            "2-D projection, height normalised to 1.0). BVH trials cached under "
            "~/.cache/hevi-cmu-mocap/ (or $HEVI_CMU_CACHE). No third-party "
            "converter used."
        ),
        "motion_count": len(motions),
        "motions": motions,
    }


def write_manifest() -> Path:
    manifest = build_manifest()
    dest = manifest_path()
    dest.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    return dest


if __name__ == "__main__":  # pragma: no cover - manual manifest helper
    dest = write_manifest()
    print(f"manifest -> {dest}")
