"""Native JianYing Pro (剪映专业版) draft writer.

The S15 survey found that the previous writer emitted an *internal* handoff
schema that happened to be called ``draft_content.json`` but was not a draft
the editor can open.  This module writes a real draft through
``pyJianYingDraft`` (Apache-2.0, dependency only -- its code is never copied
into a closed module) and ships a structural validator that compares the emitted
file against the editor-shaped template the library itself distributes.

Rules kept from the brief:

* the library is a normal Python dependency; no upstream source is vendored;
* if the library is missing, :class:`NativeDraftUnavailable` is raised rather
  than a fake draft being written;
* every material image/video/audio is copied into the draft folder, because
  the editor resolves media by the paths recorded in the draft;
* keyframes, subtitle track, audio track and transition sidecar survive the
  export;
* the result is also packaged as a zip with import instructions for the web
  download button.

The module only depends on the standard library at import time so it can be
imported in tests and tooling where the optional writer is absent.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import zipfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

__all__ = [
    "IMPORT_README",
    "NativeDraftUnavailable",
    "NativeExport",
    "NativeItem",
    "build_draft_zip",
    "library_status",
    "validate_native_draft",
    "write_native_draft",
]

TrackName = Literal["video", "audio", "text"]

IMPORT_README = """# 剪映专业版草稿导入说明 / JianYing Pro draft import

这个压缩包是 **真正的剪映专业版草稿**，不是内部交接 JSON。

## Windows / macOS 桌面版

1. 解压整个文件夹（不要只拿走 `draft_content.json`）。
2. 打开剪映专业版，进入“草稿”首页。
3. 把解压后的整个文件夹放进剪映的草稿目录（菜单：设置 → 草稿位置），
   或者直接用“导入草稿”/“打开草稿”选择这个文件夹。
4. 打开草稿后逐条检查轨道：视频、字幕、音频、关键帧。
5. 首次打开若提示素材缺失，确认 `materials/` 与 JSON 一起被拷贝（路径是
   相对/绝对混合的，草稿目录必须保持完整）。

## 注意

- 本草稿面向 **剪映专业版（JianyingPro，国内版）**；CapCut 国际版不保证可导入。
- 草稿版本是 5.9/6.x 系列；更高版本若提示升级，允许升级后再保存。
- `transitions.json` 是可编辑的转场意图边车（不是草稿格式的一部分），
  剪映内需要手动设置转场；草稿本身保留轨道、字幕、音频和关键帧。
- 素材来自 HEVI 的成片/分轨；请遵守素材自身的许可。

Generated by HEVI. pyJianYingDraft is Apache-2.0; see THIRD_PARTY_NOTICES.md.
"""


class NativeDraftUnavailable(RuntimeError):
    """The native writer is unavailable (optional dependency not installed)."""


@dataclass
class NativeItem:
    """One clip on one draft track."""

    track: TrackName
    start_s: float
    duration_s: float
    path: str = ""
    source_start_s: float = 0.0
    text: str = ""
    volume: float = 1.0
    # [{"prop": "scale"|"x"|"y"|"rotation", "at_s": seconds from clip start,
    #   "value": float}] ; ``scale`` maps to uniform_scale.
    keyframes: list[dict[str, Any]] = field(default_factory=list)
    transform_y: float = 0.0
    # optional static ClipSettings fields: alpha, scale_x, scale_y,
    # transform_x, transform_y, rotation
    transform: dict[str, float] = field(default_factory=dict)


@dataclass
class NativeExport:
    draft_dir: str
    draft_zip: str
    name: str
    duration_s: float
    files: list[str]
    manifest: dict[str, Any]

    def as_dict(self) -> dict[str, Any]:
        return {
            "draft_dir": self.draft_dir,
            "draft_zip": self.draft_zip,
            "name": self.name,
            "duration_s": self.duration_s,
            "files": self.files,
            "manifest": self.manifest,
        }


def _import_writer():  # type: ignore[no-untyped-def]
    try:  # pragma: no cover - exercised through availability branches
        import pyJianYingDraft
    except Exception as exc:  # pragma: no cover - environment dependent
        raise NativeDraftUnavailable(
            "pyJianYingDraft is not importable; install it with "
            "`pip install pyJianYingDraft` (Apache-2.0) to write native drafts"
        ) from exc
    return pyJianYingDraft


def library_status() -> dict[str, Any]:
    """Report the optional writer's availability without importing it eagerly."""
    try:
        import pyJianYingDraft  # noqa: F401

        return {
            "library": "pyJianYingDraft",
            "installed": True,
            "license": "Apache-2.0",
            "version": _pkg_version(),
        }
    except Exception as exc:
        return {
            "library": "pyJianYingDraft",
            "installed": False,
            "license": "Apache-2.0",
            "status": "not_importable",
            "detail": str(exc),
        }


def _pkg_version() -> str:
    try:
        from importlib.metadata import version

        return version("pyJianYingDraft")
    except Exception:
        return "unknown"



def _meta_template() -> str | None:
    try:
        from importlib.resources import files

        return files("pyJianYingDraft.assets").joinpath("draft_meta_info.json").read_text(
            encoding="utf-8"
        )
    except Exception:
        return None


def _hash(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()[:12]


def _safe_name(name: str) -> str:
    cleaned = "".join(ch for ch in name if ch not in '<>:"/\\|?*').strip()
    return cleaned or "hevi_draft"


def _copy_media(items: list[NativeItem], media_dir: Path) -> list[NativeItem]:
    media_dir.mkdir(parents=True, exist_ok=True)
    out: list[NativeItem] = []
    seen: dict[str, str] = {}
    for item in items:
        if item.track == "text" or not item.path:
            out.append(item)
            continue
        src = Path(item.path)
        if not src.is_file():
            raise FileNotFoundError(f"native draft material missing: {src}")
        key = str(src.resolve())
        if key in seen:
            target = seen[key]
        else:
            target = media_dir / f"{_hash(src)}_{src.name}"
            if not target.exists():
                shutil.copyfile(src, target)
            seen[key] = str(target)
        out.append(
            NativeItem(
                track=item.track,
                start_s=item.start_s,
                duration_s=item.duration_s,
                path=target,
                source_start_s=item.source_start_s,
                text=item.text,
                volume=item.volume,
                keyframes=list(item.keyframes),
                transform_y=item.transform_y,
                transform=dict(item.transform),
            )
        )
    return out


def _add_keyframes(segment: Any, item: NativeItem, kf: Any) -> None:
    mapping = {
        "scale": kf.uniform_scale,
        "x": kf.position_x,
        "y": kf.position_y,
        "rotation": kf.rotation,
        "alpha": kf.alpha,
    }
    for spec in item.keyframes:
        prop = mapping.get(str(spec.get("prop") or "scale"))
        if prop is None:
            continue
        at = max(0.0, float(spec.get("at_s") or 0.0))
        segment.add_keyframe(prop, round(at * 1_000_000), float(spec.get("value") or 1.0))


def _build_items_legacy(items: list[NativeItem]) -> list[NativeItem]:
    return list(items)


def write_native_draft(
    name: str,
    items: list[NativeItem],
    dest_dir: str | Path,
    *,
    width: int = 1920,
    height: int = 1080,
    fps: int = 30,
    copy_media: bool = True,
    package_zip: bool = True,
    transitions: list[dict[str, Any]] | None = None,
    in_place: bool = False,
) -> NativeExport:
    """Write a real JianYing Pro draft and optionally zip it with a README."""
    lib = _import_writer()
    dest = Path(dest_dir)
    dest.mkdir(parents=True, exist_ok=True)
    safe = _safe_name(name)

    # ``DraftFolder.create_draft`` creates <folder>/<name>; callers may pass
    # either a parent folder or the draft folder itself.  If dest already
    # contains draft_content.json, write in place.
    in_place = in_place or (dest / "draft_content.json").exists()
    if in_place:
        # Never let DraftFolder.create_draft() wipe an existing folder: P5
        # builders copy media into it before calling us.
        dest.mkdir(parents=True, exist_ok=True)
        draft_name = dest.name
        script = lib.ScriptFile(width, height, fps, True)
        script.save_path = str(dest / "draft_content.json")
        meta_path = dest / "draft_meta_info.json"
        if not meta_path.exists():
            template = _meta_template()
            if template is not None:
                meta_path.write_text(template, encoding="utf-8")
    else:
        root = dest
        draft_name = safe
        folder = lib.DraftFolder(str(root))
        script = folder.create_draft(draft_name, width, height, fps=fps, allow_replace=True)
    script.save_path  # noqa: B018 - property exists on ScriptFile

    if copy_media:
        items = _copy_media(items, Path(script.save_path).parent / "materials")
    else:  # pragma: no cover - copied media is the safe default
        items = _build_items_legacy(items)

    # One editor track per non-overlapping lane: a background clip and a
    # picture-in-picture evidence clip both start at 0 and must not collide.
    lane_ends: dict[str, list[float]] = {"video": [], "audio": [], "text": []}
    lane_refs: dict[str, list[Any]] = {"video": [], "audio": [], "text": []}

    def track_for(kind: str, start_s: float, end_s: float):  # type: ignore[no-untyped-def]
        lanes = lane_ends[kind]
        for index, lane_end in enumerate(lanes):
            if start_s >= lane_end - 1e-6:
                lanes[index] = end_s
                return lane_refs[kind][index]
        ref = script.append_track(
            lib.TrackSpec(getattr(lib.TrackType, kind), name=f"{kind}_{len(lane_refs[kind]) + 1}")
        )
        lane_ends[kind].append(end_s)
        lane_refs[kind].append(ref)
        return ref

    for item in items:
        start = round(max(0.0, float(item.start_s)) * 1_000_000)
        duration = round(max(0.01, float(item.duration_s)) * 1_000_000)
        src_start = round(max(0.0, float(item.source_start_s)) * 1_000_000)
        target = lib.Timerange(start, duration)
        source = lib.Timerange(src_start, duration)
        settings = item.transform or {}
        clip_settings = lib.ClipSettings(
            alpha=float(settings.get("alpha", 1.0)),
            scale_x=float(settings.get("scale_x", 1.0)),
            scale_y=float(settings.get("scale_y", 1.0)),
            transform_x=float(settings.get("transform_x", 0.0)),
            transform_y=float(settings.get("transform_y", item.transform_y or 0.0)),
            rotation=float(settings.get("rotation", 0.0)),
        )
        if item.track == "text":
            style = lib.TextStyle(size=8.0, align=1)
            if not settings:
                clip_settings = lib.ClipSettings(transform_y=item.transform_y or -0.78)
            segment = lib.TextSegment(
                item.text or " ", target, style=style, clip_settings=clip_settings,
            )
        elif item.track == "audio":
            segment = lib.AudioSegment(
                str(item.path), target, volume=max(0.0, min(1.0, float(item.volume))),
                source_timerange=source,
            )
        else:
            segment = lib.VideoSegment(
                str(item.path), target,
                source_timerange=source,
                volume=max(0.0, min(1.0, float(item.volume))),
                clip_settings=clip_settings,
            )
        script.add_segment(segment, track_for(item.track, item.start_s, item.start_s + item.duration_s))
        _add_keyframes(segment, item, lib.KeyframeProperty)

    script.save()

    draft_dir = Path(script.save_path).parent
    _stamp_meta(draft_dir, draft_name, width, height, fps)
    (draft_dir / "IMPORT_README.md").write_text(IMPORT_README, encoding="utf-8")
    if transitions:
        (draft_dir / "transitions.json").write_text(
            json.dumps(transitions, ensure_ascii=False, indent=2), encoding="utf-8"
        )

    manifest = {
        "format": "jianying_native",
        "writer": "pyJianYingDraft",
        "license": "Apache-2.0",
        "library_version": _pkg_version(),
        "draft_name": draft_name,
        "canvas": {"width": width, "height": height, "fps": fps},
        "tracks": {
            kind: sum(1 for i in items if i.track == kind) for kind in ("video", "audio", "text")
        },
        "duration_s": round(max((i.start_s + i.duration_s for i in items), default=0.0), 3),
        "materials": [
            {"track": i.track, "path": Path(i.path).name if i.path else "", "text": i.text}
            for i in items
        ],
    }
    (draft_dir / "hevi_export_manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    files = sorted(str(p.relative_to(draft_dir)) for p in draft_dir.rglob("*") if p.is_file())
    zip_path = ""
    if package_zip:
        zip_path = str(build_draft_zip(draft_dir))
    return NativeExport(
        draft_dir=str(draft_dir),
        draft_zip=zip_path,
        name=draft_name,
        duration_s=manifest["duration_s"],
        files=files,
        manifest=manifest,
    )


def _stamp_meta(draft_dir: Path, draft_name: str, width: int, height: int, fps: int) -> None:
    """Fill the fields the library's template leaves empty (name/path/duration)."""
    meta_path = draft_dir / "draft_meta_info.json"
    if not meta_path.is_file():
        return
    try:
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return
    content_path = draft_dir / "draft_content.json"
    try:
        content = json.loads(content_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        content = {}
    meta["draft_name"] = draft_name
    meta["draft_fold_path"] = str(draft_dir.resolve())
    meta["draft_root_path"] = str(draft_dir.resolve().parent)
    meta["tm_duration"] = int(content.get("duration") or 0)
    meta_path.write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")


def build_draft_zip(draft_dir: str | Path) -> Path:
    src = Path(draft_dir)
    if not src.is_dir():
        raise FileNotFoundError(f"draft folder missing: {src}")
    target = src.with_suffix(".zip") if src.suffix != ".zip" else src.with_name(src.stem)
    if not str(target).endswith(".zip"):
        target = Path(str(target) + ".zip")
    with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(src.rglob("*")):
            if path.is_file():
                zf.write(path, arcname=str(Path(src.name) / path.relative_to(src)))
        # import instructions at the root too, so a user who never opens the
        # draft folder still sees them
        readme = src / "IMPORT_README.md"
        if readme.is_file():
            zf.write(readme, arcname="IMPORT_README.md")
    return target


# ── validation ────────────────────────────────────────────────────────────

_REQUIRED_TOP = {
    "version",
    "id",
    "fps",
    "duration",
    "canvas_config",
    "config",
    "materials",
    "tracks",
    "platform",
    "keyframes",
    "relationships",
}
_SEGMENT_KEYS = {
    "id",
    "material_id",
    "target_timerange",
    "source_timerange",
    "extra_material_refs",
    "clip",
    "common_keyframes",
}
_META_KEYS = {"draft_name", "tm_duration", "draft_fold_path", "draft_root_path", "draft_id"}


def _reference_template() -> dict[str, Any] | None:
    try:
        from importlib.resources import files

        path = files("pyJianYingDraft.assets").joinpath("draft_content_template.json")
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None


def validate_native_draft(
    draft_dir: str | Path, *, reference: dict[str, Any] | None = None
) -> dict[str, Any]:
    """Validate a native draft against the editor-shaped schema.

    Returns ``{"valid": bool, "errors": [...], "warnings": [...],
    "stats": {...}, "schema_diff": {...}}``.  ``schema_diff`` compares the
    top-level key set with ``pyJianYingDraft``'s bundled real template (when
    available) or with a caller-supplied reference.
    """
    root = Path(draft_dir)
    errors: list[str] = []
    warnings: list[str] = []
    content_path = root / "draft_content.json"
    meta_path = root / "draft_meta_info.json"
    if not content_path.is_file():
        return {"valid": False, "errors": ["draft_content.json missing"],
                "warnings": [], "stats": {}, "schema_diff": {}}
    if not meta_path.is_file():
        errors.append("draft_meta_info.json missing")
    try:
        content = json.loads(content_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return {"valid": False, "errors": [f"draft_content.json unreadable: {exc}"],
                "warnings": [], "stats": {}, "schema_diff": {}}
    meta: dict[str, Any] = {}
    if meta_path.is_file():
        try:
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            errors.append(f"draft_meta_info.json unreadable: {exc}")

    missing = sorted(_REQUIRED_TOP - set(content))
    if missing:
        errors.append(f"missing top-level keys: {missing}")
    materials = content.get("materials")
    if not isinstance(materials, dict):
        errors.append("materials must be an object of material buckets (not a list)")
    tracks = content.get("tracks")
    if not isinstance(tracks, list) or not tracks:
        errors.append("tracks must be a non-empty list")

    material_ids: set[str] = set()
    if isinstance(materials, dict):
        for bucket, values in materials.items():
            if not isinstance(values, list):
                warnings.append(f"material bucket {bucket} is not a list")
                continue
            for entry in values:
                if isinstance(entry, dict) and entry.get("id"):
                    material_ids.add(str(entry["id"]))

    video_count = audio_count = text_count = 0
    keyframe_count = 0
    if isinstance(tracks, list):
        for track in tracks:
            if not isinstance(track, dict) or not isinstance(track.get("segments"), list):
                errors.append("track is missing a segments list")
                continue
            kind = str(track.get("type") or "")
            for seg in track["segments"]:
                if not isinstance(seg, dict):
                    errors.append(f"track {kind}: segment is not an object")
                    continue
                missing_seg = sorted(_SEGMENT_KEYS - set(seg))
                if missing_seg:
                    errors.append(f"track {kind}: segment missing {missing_seg}")
                mid = str(seg.get("material_id") or "")
                if mid and material_ids and mid not in material_ids:
                    # text segments reference a text material; video/audio
                    # reference a video/audio material.  Both must exist.
                    errors.append(f"track {kind}: material_id {mid} not in materials")
                if kind == "video":
                    video_count += 1
                elif kind == "audio":
                    audio_count += 1
                elif kind == "text":
                    text_count += 1
                kfs = seg.get("common_keyframes")
                if isinstance(kfs, list):
                    for entry in kfs:
                        if isinstance(entry, dict) and entry.get("keyframe_list"):
                            keyframe_count += len(entry["keyframe_list"])
                warnings.extend(
                    f"track {kind}: extra_material_ref {ref} not found"
                    for ref in (seg.get("extra_material_refs") or [])
                    if material_ids and str(ref) not in material_ids
                )
                tgt = seg.get("target_timerange") or {}
                if not isinstance(tgt.get("duration"), int) or tgt.get("duration", 0) <= 0:
                    errors.append(f"track {kind}: target_timerange.duration must be positive")

    # media files must exist inside the draft folder
    if isinstance(materials, dict):
        for bucket, values in materials.items():
            if bucket not in {"videos", "audios", "images"}:
                continue
            for entry in values:
                raw = str((entry or {}).get("path") or "")
                if not raw:
                    continue
                p = Path(raw)
                if not p.is_absolute():
                    p = root / p
                if not p.exists():
                    errors.append(f"material file missing: {p}")
                elif root not in p.resolve().parents and p.resolve() != root.resolve():
                    warnings.append(f"material outside draft folder: {p}")

    meta_missing = sorted(_META_KEYS - set(meta)) if meta else sorted(_META_KEYS)
    if meta_missing:
        errors.append(f"draft_meta_info missing keys: {meta_missing}")

    ref = reference if reference is not None else _reference_template()
    schema_diff: dict[str, Any] = {}
    if isinstance(ref, dict):
        schema_diff = {
            "reference": "pyJianYingDraft assets/draft_content_template.json"
            if reference is None else "caller_supplied",
            "missing_top_keys": sorted(set(ref) - set(content)),
            "extra_top_keys": sorted(set(content) - set(ref)),
            "reference_top_key_count": len(ref),
            "draft_top_key_count": len(content),
        }
        if schema_diff["missing_top_keys"]:
            errors.append(f"draft misses reference keys: {schema_diff['missing_top_keys']}")

    stats = {
        "top_keys": len(content),
        "material_buckets": len(materials) if isinstance(materials, dict) else 0,
        "tracks": {"video": video_count, "audio": audio_count, "text": text_count},
        "keyframes": keyframe_count,
        "duration_us": content.get("duration"),
        "fps": content.get("fps"),
        "canvas": content.get("canvas_config"),
        "bytes": content_path.stat().st_size,
    }
    return {
        "valid": not errors,
        "errors": errors,
        "warnings": warnings,
        "stats": stats,
        "schema_diff": schema_diff,
    }


def items_from_shots(shots: list[dict[str, Any]]) -> list[NativeItem]:
    """Map a shot plan (``start_sec``/``end_sec``) to native draft items.

    Recognised per-shot keys: ``image`` or ``path`` (video/image clip),
    ``audio`` (narration/voice), ``sentence_text`` or ``caption`` (subtitle).
    Shots without media still produce a subtitle-only entry when text exists;
    nothing is invented for a shot with neither.
    """
    items: list[NativeItem] = []
    for shot in shots:
        start = float(shot.get("start_sec") or 0.0)
        end = float(shot.get("end_sec") or start)
        dur = max(0.04, end - start)
        media = str(shot.get("path") or shot.get("image") or "")
        if media:
            items.append(NativeItem(track="video", start_s=start, duration_s=dur, path=media))
        audio = str(shot.get("audio") or "")
        if audio:
            items.append(NativeItem(track="audio", start_s=start, duration_s=dur, path=audio))
        text = str(shot.get("sentence_text") or shot.get("caption") or "").strip()
        if text:
            items.append(NativeItem(track="text", start_s=start, duration_s=dur, text=text))
    return items


def shots_have_media(shots: list[dict[str, Any]]) -> bool:
    return any(str(s.get("path") or s.get("image") or s.get("audio") or "") for s in shots)
