"""Generation-unit splitter (``story.generation_unit_splitter``).

Clean-room rewrite of the *splitting discipline* in the
rea-video field report (``hevi-vs-rea-video.md`` section 2.2,
rules S01-S07, restated in our own words): an edited film is
cut into generation units before any model is called. A unit
is by default 4 to 15 seconds long. Consecutive shots in the
same scene may be merged into one unit. A unit that runs over
the ceiling is split at an action pause, and the following
unit starts from the previous unit's tail frame. Inside one
unit, consecutive hard cuts should total about 8 seconds and
never more than about 10. Text and interface elements are
pulled out into a code layer, because a generative model
redrawing text will get it wrong.

Shape: ``{"shots": [{"id", "scene", "start_s", "end_s",
"action_pause_after": bool, "has_text_ui": bool}], "unit_max_s":
15, "unit_min_s": 4, "hard_cut_budget_s": 8}``. Durations are
caller-supplied; the splitter never invents timings. Every
output unit carries its source shot ids, its tail-frame
carryover, and the text/UI items extracted to the code layer.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from hevi.capabilities.errors import CapabilityError
from hevi.capabilities.registry import (
    Capability,
    CapabilityResult,
    compute_sha256,
    register,
)

DEFAULT_MIN_S = 4.0
DEFAULT_MAX_S = 15.0
HARD_CUT_BUDGET_S = 8.0
HARD_CUT_MAX_S = 10.0


def split_generation_units(
    shots: list[dict[str, Any]] | None,
    *,
    unit_min_s: float = DEFAULT_MIN_S,
    unit_max_s: float = DEFAULT_MAX_S,
    hard_cut_budget_s: float = HARD_CUT_BUDGET_S,
) -> dict[str, Any]:
    """Split edited shots into generation units under S01-S07."""
    if not isinstance(shots, list) or not shots:
        raise CapabilityError("generation-unit splitter needs a non-empty shots list")
    ordered = sorted(shots, key=lambda s: s.get("start_s", 0.0))
    units: list[dict[str, Any]] = []
    code_layer: list[dict[str, Any]] = []
    current: list[dict[str, Any]] = []
    current_start: float | None = None

    def flush() -> None:
        nonlocal current, current_start
        if not current:
            return
        end = max(float(s["end_s"]) for s in current)
        start = float(current_start) if current_start is not None else 0.0
        units.append(
            {
                "shot_ids": [s["id"] for s in current],
                "scene": current[0].get("scene"),
                "start_s": start,
                "end_s": end,
                "duration_s": round(end - start, 3),
                "tail_frame_carryover_from": (
                    units[-1]["shot_ids"][-1] if units else None
                ),
            }
        )
        current = []
        current_start = None

    for shot in ordered:
        if not isinstance(shot, dict) or shot.get("id") is None:
            raise CapabilityError("every shot needs an id")
        start = float(shot.get("start_s", 0.0))
        end = float(shot.get("end_s", 0.0))
        if end <= start:
            raise CapabilityError(f"shot {shot['id']!r} has non-positive duration")
        if shot.get("has_text_ui"):
            code_layer.append(
                {"shot_id": shot["id"], "extracted": "text_ui",
                 "note": "text/UI pulled to the code layer; never regenerated by a model"}
            )
        if current and current[0].get("scene") != shot.get("scene"):
            flush()
        if current:
            projected = end - float(current_start)
            if projected > unit_max_s:
                if not current[-1].get("action_pause_after"):
                    raise CapabilityError(
                        f"unit over {unit_max_s}s at shot {shot['id']!r} "
                        "without an action pause to split on"
                    )
                flush()
        if current_start is None:
            current_start = start
        current.append(shot)
    flush()
    issues: list[str] = []
    for unit in units:
        if unit["duration_s"] < unit_min_s:
            issues.append(
                f"short_unit: {unit['shot_ids']} is {unit['duration_s']}s, "
                f"below the {unit_min_s}s default floor"
            )
        if unit["duration_s"] > unit_max_s:
            issues.append(f"overlong_unit: {unit['shot_ids']}")
    hard_cut_total = sum(
        float(s["end_s"]) - float(s["start_s"]) for s in ordered
    )
    if hard_cut_total > HARD_CUT_MAX_S and len(units) == 1:
        issues.append(
            f"hard_cut_overrun: single unit spans {hard_cut_total}s of "
            f"hard cuts over the {HARD_CUT_MAX_S}s ceiling"
        )
    return {
        "units": units,
        "code_layer": code_layer,
        "unit_min_s": unit_min_s,
        "unit_max_s": unit_max_s,
        "hard_cut_budget_s": hard_cut_budget_s,
        "hard_cut_max_s": HARD_CUT_MAX_S,
        "issues": issues,
        "ok": not issues,
    }


def _render(params: dict[str, Any], out_dir: Path, *, duration: float,
            aspect: str, seed: int) -> CapabilityResult:
    report = split_generation_units(
        params.get("shots"),
        unit_min_s=params.get("unit_min_s", DEFAULT_MIN_S),
        unit_max_s=params.get("unit_max_s", DEFAULT_MAX_S),
        hard_cut_budget_s=params.get("hard_cut_budget_s", HARD_CUT_BUDGET_S),
    )
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    report_path = out_dir / "generation_units.json"
    report_path.write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return CapabilityResult(
        duration_s=0.0,
        sha256=compute_sha256(report_path),
        qa={
            "report_json": str(report_path),
            "units": len(report["units"]),
            "ok": report["ok"],
        },
    )


_Registered = False


def register_generation_unit_splitter_capabilities_once() -> list[str]:
    global _Registered
    if _Registered:
        return []
    _Registered = True
    register(
        Capability(
            name="story.generation_unit_splitter",
            kind="line",
            aspects=["16:9", "9:16", "1:1"],
            params_schema={
                "type": "object",
                "properties": {
                    "shots": {"type": "array"},
                    "unit_min_s": {"type": "number"},
                    "unit_max_s": {"type": "number"},
                    "hard_cut_budget_s": {"type": "number"},
                },
                "required": ["shots"],
                "additionalProperties": False,
            },
            cpu_cost_hint=0.0,
            render=_render,
            has_media_output=False,
            description=(
                "Generation-unit splitter (rea-video B3, clean-room): "
                "edited shots to 4-15s units, tail-frame carryover, "
                "text/UI extracted to the code layer. See "
                "REA_VIDEO_ATTRIBUTION.md."
            ),
            line="story",
        )
    )
    return ["story.generation_unit_splitter"]


register_generation_unit_splitter_capabilities_once()
