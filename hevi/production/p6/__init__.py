"""HEVI P6 — Commercial Product Grammar.

A single commercial product layer over the existing P0-P5 engine. One
``ProductProfile`` and a composable grammar set describe *what kind of video is
being made*; the existing runtime still decides *how it is made*.

P6 is intent and constraint only. It does not own a pipeline, renderer,
timeline, shot model, motion model, asset authority, evidence authority, QA
authority, or provider selection. See :mod:`hevi.production.p6.schema` for the
per-authority statement and ``docs/P6-0-AUTHORITY-BOUNDARY.md`` for the audit.

P6.0 is architecture: schemas, registries, compiler contract, runtime boundary.
Grammar behaviour and compilation arrive in P6.1+.
"""

