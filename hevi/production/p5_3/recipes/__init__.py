"""HEVI P5.3 — initial recipe set: 63 hand-qualified structured recipes.

Quality over quantity. Each recipe is a typed structured contract describing
WHAT the viewer sees, WHY it serves the story, WHEN it applies, and HOW it is
composed. No recipe is a prompt string.
"""

from __future__ import annotations

from typing import Any

from hevi.production.p5_3.schema import (
    CinematicRecipe,
    LicenseProvenance,
    QualificationState,
    RecipeFamily,
    SourceProvenance,
)


def _recipe(
    recipe_id: str,
    family: RecipeFamily,
    name: str,
    description: str,
    *,
    intent: str = "",
    semantic_roles: list[str] | None = None,
    profiles: list[str] | None = None,
    beat_roles: list[str] | None = None,
    composition: str = "",
    subject_role: str = "",
    evidence_role: str = "",
    background_role: str = "",
    entry: str = "",
    hold: str = "",
    exit: str = "",
    camera: str = "",
    motion: str = "",
    transition: str = "",
    duration: tuple[float, float] = (2.0, 5.0),
    density: tuple[float, float] = (0.3, 0.7),
    required_assets: list[str] | None = None,
    optional_assets: list[str] | None = None,
    capabilities: list[str] | None = None,
    parameters: dict[str, Any] | None = None,
    constraints: dict[str, Any] | None = None,
    anti_patterns: list[str] | None = None,
    renderer_reqs: list[str] | None = None,
    renderer_prefs: list[str] | None = None,
    prompt_hint: str = "",
) -> CinematicRecipe:
    """Build a recipe with sensible defaults, so each recipe states only what is distinctive."""
    # required_capabilities defaults to renderer_reqs when not explicitly set,
    # so a recipe that needs TEXT/SVG is discoverable by capability search.
    effective_capabilities = capabilities if capabilities is not None else (renderer_reqs or [])
    return CinematicRecipe(
        recipe_id=recipe_id,
        version="1.0.0",
        recipe_family=family,
        name=name,
        description=description,
        intent=intent,
        semantic_roles=semantic_roles or [],
        profile_compatibility=profiles or [],
        beat_roles=beat_roles or [],
        composition=composition,
        subject_role=subject_role,
        evidence_role=evidence_role,
        background_role=background_role,
        entry_behavior=entry,
        hold_behavior=hold,
        exit_behavior=exit,
        camera_behavior=camera,
        motion_behavior=motion,
        transition_behavior=transition,
        duration_range=duration,
        information_density_range=density,
        required_assets=required_assets or [],
        optional_assets=optional_assets or [],
        required_capabilities=effective_capabilities,
        parameters=parameters or {},
        constraints=constraints or {},
        anti_patterns=anti_patterns or [],
        renderer_requirements=renderer_reqs or [],
        renderer_preferences=renderer_prefs or [],
        source_provenance=SourceProvenance(origin="hand_crafted"),
        license_provenance=LicenseProvenance(license="HEVI-internal", license_confidence="verified"),
        qualification_state=QualificationState.EXPERIMENTAL,
        prompt_hint=prompt_hint,
    )


