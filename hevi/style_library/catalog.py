def recommend(topic: str = "", *, mood: str = "", platform: str = "", style_hint: str = "") -> dict[str, Any]:
    text = f"{topic} {mood}".lower()
    chosen = _DEFAULT
    for keywords, target, reason in _MOODS:
        if any(k.lower() in text for k in keywords):
            chosen = (target, reason)
            break
    target, reason = chosen
    styles = [
        s for s in load_index()["styles"]
        if s.get("category") in target["categories"]
    ]
    if not styles:
        styles = load_index()["styles"]
    # Deterministic rotation inside the category so different topics do not all
    # land on the first item; the topic hash makes it stable across sessions.
    seed = int(hashlib.sha256(topic.encode("utf-8")).hexdigest()[:8], 16)
    if style_hint:
        try:
            style = get_style(style_hint)
        except StyleLibraryError:
            style = styles[seed % len(styles)]
    else:
        style = styles[seed % len(styles)]
    color = get_color(target["color"])
    layout = get_layout(target["layout"]) if target.get("layout") else None
    platform_note = {
        "xiaohongshu": "小红书 3:4，标题短、信息点少。",
        "douyin": "抖音 9:16，前 3 秒大字钩子。",
        "wechat": "公众号 16:9 题图 + 正文长图。",
        "video": "视频关键帧按 16:9 或 9:16 锁定同一主题色。",
    }.get(platform, "")
    return {
        "style": style_brief(style),
        "theme_color": color,
        "layout": layout,
        "reason": reason + (" " + platform_note if platform_note else ""),
        "locked": {"style_id": style["id"], "theme_color_id": color["id"]},
        "attribution": ATTRIBUTION,
    }


