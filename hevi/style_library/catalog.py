"""Search, recommend and render the handraw-style catalogue.

The index is local and offline.  Nothing here calls a paid image model.
Previews are generated by hevi from the style traits and category (never
copied from the upstream image gallery), so the selector has no third-party
image assets and no attribution ambiguity.
"""

from __future__ import annotations

import hashlib
import json
from functools import lru_cache
from pathlib import Path
from typing import Any, cast

from hevi.style_library import ATTRIBUTION as ATTRIBUTION
from hevi.style_library import ATTRIBUTION_URL, LICENSE_NOTE

_INDEX_PATH = (
    Path(__file__).resolve().parents[1] / "image" / "handraw_data" / "handraw_index.json"
)


class StyleLibraryError(ValueError):
    """Unknown id or malformed request."""


@lru_cache(maxsize=1)
def load_index() -> dict[str, Any]:
    if not _INDEX_PATH.exists():
        raise StyleLibraryError(
            f"handraw index missing at {_INDEX_PATH}; rebuild with "
            "hevi/image/handraw_data/build_handraw_index.py"
        )
    return cast(dict[str, Any], json.loads(_INDEX_PATH.read_text(encoding="utf-8")))


def counts() -> dict[str, int]:
    return dict(load_index()["counts"])


def meta() -> dict[str, Any]:
    index = load_index()
    return {
        "source": index["source"],
        "upstream_version": index.get("upstream_version", ""),
        "attribution": index.get("attribution", ATTRIBUTION),
        "license": LICENSE_NOTE,
        "counts": index["counts"],
        "groups": index.get("groups", []),
        "credit_removed": index.get("credit_policy", {}).get("removed_entries", 0),
    }


def _norm(raw: Any) -> str:
    return str(raw or "").strip()


def canonical_style_id(raw: Any) -> str:
    index = load_index()
    text = _norm(raw)
    if text.isdigit():
        return str(index["legacy_to_new"].get(f"{int(text):03}", f"{int(text):03}"))
    import re

    m = re.match(r"^([A-Za-z]{2})[-_]?(\d+)$", text)
    if m:
        return f"{m.group(1).upper()}-{int(m.group(2)):03}"
    return text.upper()


def get_style(raw: Any) -> dict[str, Any]:
    canonical = canonical_style_id(raw)
    for style in load_index()["styles"]:
        if style["id"] == canonical:
            return dict(style)
    legacy_to_new = load_index()["legacy_to_new"]
    if canonical in legacy_to_new:
        target = legacy_to_new[canonical]
        for style in load_index()["styles"]:
            if style["id"] == target:
                return dict(style)
    raise StyleLibraryError(f"unknown style id: {raw!r}")


def _canonical_layout(raw: Any) -> str:
    import re

    text = _norm(raw)
    m = re.match(r"^([A-Za-z]{2,3})[-_]?(\d+)$", text)
    return f"{m.group(1).upper()}-{int(m.group(2)):03}" if m else text.upper()


def get_layout(raw: Any) -> dict[str, Any]:
    canonical = _canonical_layout(raw)
    for layout in load_index()["layouts"]:
        if layout["id"] == canonical:
            return dict(layout)
    raise StyleLibraryError(f"unknown layout id: {raw!r}")


def get_color(raw: Any) -> dict[str, Any]:
    import re

    text = _norm(raw)
    m = re.match(r"^[Cc][-]?(\d+)$", text)
    canonical = f"C-{int(m.group(1)):02}" if m else ""
    for color in load_index()["colors"]:
        if canonical and color["id"] == canonical:
            return dict(color)
        if text in (color["name_zh"], color["name_en"]):
            return dict(color)
    raise StyleLibraryError(f"unknown theme color: {raw!r} (C-01..C-36)")


def style_brief(style: dict[str, Any]) -> dict[str, Any]:
    return {
        "id": style["id"],
        "legacy_number": style.get("legacy_number", ""),
        "name": style.get("generation_name", ""),
        "category": style.get("category", ""),
        "group": style.get("group", ""),
        "use_cases": style.get("use_cases", []),
        "traits": style.get("traits", ""),
        "credit": style.get("reference", ""),
        "credit_removed": bool(style.get("credit_removed")),
        "preview": f"/api/style-library/preview/{style['id']}.svg",
    }


def search(
    section: str = "styles",
    *,
    query: str = "",
    category: str = "",
    use_case: str = "",
    limit: int = 60,
    offset: int = 0,
) -> dict[str, Any]:
    """Search one section.  Matches ids, legacy numbers, names, traits, groups."""
    index = load_index()
    if section not in {"styles", "layouts", "colors", "tones"}:
        raise StyleLibraryError(f"unknown section: {section!r}")
    q = _norm(query).lower()
    cat = _norm(category).upper()
    use = _norm(use_case)
    items = index[section]
    hits: list[dict[str, Any]] = []
    for item in items:
        if cat:
            item_cat = str(item.get("category", "")).upper()
            if not (item_cat == cat or item_cat.startswith(cat) or str(item.get("group", "")).startswith(cat)):
                continue
        if use and use not in (item.get("use_cases") or []):
            continue
        if q:
            haystack = " ".join(
                str(item.get(k, ""))
                for k in (
                    "id", "legacy_number", "name", "name_zh", "name_en",
                    "generation_name", "group", "traits", "keywords",
                    "use_cases", "reference",
                )
            ).lower()
            if q not in haystack:
                continue
        hits.append(item)
    total = len(hits)
    page = hits[offset : offset + max(1, min(limit, 500))]
    out = {
        "section": section,
        "query": query,
        "category": category,
        "use_case": use_case,
        "total": total,
        "offset": offset,
        "returned": len(page),
        "attribution": ATTRIBUTION,
    }
    if section == "styles":
        out["styles"] = [style_brief(item) for item in page]
    else:
        out[section] = page
    return out


