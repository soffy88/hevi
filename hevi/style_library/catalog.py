def _rgb(hex_code: str) -> tuple[int, int, int]:
    clean = str(hex_code or "").lstrip("#")
    if len(clean) != 6:
        return (200, 169, 106)
    return int(clean[0:2], 16), int(clean[2:4], 16), int(clean[4:6], 16)


def _hex(rgb: tuple[int, int, int]) -> str:
    return "#" + "".join(f"{max(0, min(255, round(c))):02X}" for c in rgb)


def _mix(a: tuple[int, int, int], b: tuple[int, int, int], t: float) -> tuple[int, int, int]:
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))  # type: ignore[return-value]


def _luma(rgb: tuple[int, int, int]) -> float:
    return (0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2]) / 255.0


def theme_palette(color_id: str = "C-27") -> dict[str, Any]:
    """A legible dark palette driven by one library theme colour.

    Same role names as the warm-gold card so the explainer/cover/S24 renderers
    can accept it without a new contract.  The accent is the library colour;
    text stays ivory; the danger red is only for negative/threat.
    """
    color = get_color(color_id)
    accent = _rgb(color.get("hex") or "#C8A96A")
    # Keep the accent readable on a dark field.
    if _luma(accent) < 0.16:
        accent_ui = _mix(accent, (255, 255, 255), 0.28)
    elif _luma(accent) > 0.72:
        accent_ui = _mix(accent, (0, 0, 0), 0.22)
    else:
        accent_ui = accent
    background = _mix(_mix(accent, (14, 10, 8), 0.88), (0, 0, 0), 0.16)
    panel = _mix(background, accent, 0.10)
    ivory = _mix((255, 250, 240), accent, 0.08)
    ivory_dim = _mix(ivory, background, 0.42)
    past = _mix(ivory, background, 0.66)
    danger = (122, 46, 42)
    return {
        "id": color["id"],
        "name": color.get("name_zh", ""),
        "name_en": color.get("name_en", ""),
        "hex": color.get("hex", ""),
        "background": _hex(background),
        "background_soft": _hex(_mix(background, accent, 0.06)),
        "panel": _hex(panel),
        "ivory": _hex(ivory),
        "ivory_dim": _hex(ivory_dim),
        "gold": _hex(accent_ui),
        "gold_bright": _hex(_mix(accent_ui, (255, 255, 255), 0.20)),
        "accent": _hex(accent_ui),
        "danger": _hex(danger),
        "past": _hex(past),
        "on_accent": "#0E0A08" if _luma(accent_ui) > 0.55 else "#FFFFFF",
    }


